"""Sample both countries at one geographic scale, without third-party packages.

Run: python3 scripts/generate-pixel-maps.py /path/to/ne_50m_admin_0_countries.geojson
Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_admin_0_countries.geojson
Natural Earth data is public domain: https://www.naturalearthdata.com/about/terms-of-use/
"""

import argparse
import bisect
import hashlib
import json
import math
from pathlib import Path


EARTH_RADIUS_KM = 6371.0071809  # Authalic Earth sphere.
CELL_KM = 60


def project(point):
    """Shared north-polar Lambert azimuthal equal-area, lon_0=0, lat_0=90."""
    longitude, latitude = map(math.radians, point[:2])
    radius = EARTH_RADIUS_KM * math.sqrt(2 * (1 - math.sin(latitude)))
    return radius * math.sin(longitude), -radius * math.cos(longitude)


def orient(point, meridian):
    """Rigid north-up display rotation only: no country-specific scale or projection."""
    x, y = project(point)
    angle = math.radians(meridian)
    return (
        x * math.cos(angle) + y * math.sin(angle),
        x * math.sin(angle) - y * math.cos(angle),  # SVG's y axis points down.
    )


def ring_area(ring):
    return abs(sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(ring, ring[1:]))) / 2


def sample(geometry, meridian):
    polygons = [[list(orient(point, meridian) for point in ring)
                 for ring in polygon] for polygon in geometry['coordinates']]
    points = [point for polygon in polygons for ring in polygon for point in ring]
    start_x = math.floor(min(x for x, _ in points) / CELL_KM) - 1
    start_y = math.floor(min(y for _, y in points) / CELL_KM) - 1
    columns = math.ceil(max(x for x, _ in points) / CELL_KM) - start_x + 1
    height = math.ceil(max(y for _, y in points) / CELL_KM) - start_y + 1
    rows = []

    for row in range(height):
        y = (start_y + row + 0.5) * CELL_KM
        crossings = []
        for polygon in polygons:
            intersections = []
            for ring in polygon:
                for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
                    if (y1 > y) != (y2 > y):
                        intersections.append(x1 + (y - y1) * (x2 - x1) / (y2 - y1))
            crossings.append(sorted(intersections))
        rows.append(''.join(
            'o' if any(bisect.bisect_right(xs, (start_x + col + 0.5) * CELL_KM) % 2
                       for xs in crossings) else ' '
            for col in range(columns)
        ).rstrip())

    area = sum(ring_area(polygon[0]) - sum(map(ring_area, polygon[1:]))
               for polygon in polygons)
    dot_count = sum(row.count('o') for row in rows)
    sampled_area = dot_count * CELL_KM ** 2
    assert abs(sampled_area / area - 1) < 0.02, 'Sampling must preserve area within 2%'
    return {
        'columns': columns,
        'cellKilometers': CELL_KM,
        'projectedAreaSquareKilometers': round(area),
        'sampledAreaSquareKilometers': sampled_area,
        'rows': rows,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    features = json.loads(args.source.read_text())['features']
    maps = {}
    for name, meridian in [('China', 105), ('Canada', -96)]:
        geometry = next(feature['geometry'] for feature in features
                        if feature['properties']['ADMIN'] == name)
        maps[name.lower()] = sample(geometry, meridian)

    geographic_ratio = (maps['canada']['projectedAreaSquareKilometers']
                        / maps['china']['projectedAreaSquareKilometers'])
    dot_ratio = (maps['canada']['sampledAreaSquareKilometers']
                 / maps['china']['sampledAreaSquareKilometers'])
    assert abs(dot_ratio / geographic_ratio - 1) < 0.02

    header = f'''// Generated by scripts/generate-pixel-maps.py; do not hand-edit the silhouettes.
// Natural Earth 1:50m country polygons, public domain; polygon holes/islands sampled.
// Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_admin_0_countries.geojson
// Source SHA-256: {hashlib.sha256(args.source.read_bytes()).hexdigest()}
// ONE projection: north-polar Lambert azimuthal equal-area (lat_0=90, lon_0=0),
// authalic Earth radius {EARTH_RADIUS_KM} km. Each grid cell is {CELL_KM} km for BOTH countries.
// North-up display rotations/translations preserve area and distance scale;
// no per-country normalization or fitting to a common bounding box.
// CSS supplies one shared pixels-per-cell value, including responsive resizing.

'''
    output = Path(__file__).resolve().parents[1] / 'src/data/pixelMaps.js'
    output.write_text(header + 'export const pixelMaps = ' + json.dumps(maps, indent=2) + '\n')
    for name, data in maps.items():
        print(f"{name}: {data['columns']}×{len(data['rows'])} cells, "
              f"area {data['projectedAreaSquareKilometers']:,} km², "
              f"sampled {data['sampledAreaSquareKilometers']:,} km²")
    print(f'Canada/China projected area ratio: {geographic_ratio:.4f}; dot ratio: {dot_ratio:.4f}')


if __name__ == '__main__':
    main()
